def skill_filter(skill: str) -> models.Filter:
    """Build a Qdrant filter that keeps only records tagged with a given skill.

    The filter checks the ``metadata.skill`` field of each stored record's
    payload and keeps only records whose value is exactly equal to ``skill``.
    It is intended to be passed as the ``query_filter`` argument of a search
    or scroll call so that vector results are restricted to one skill.

    The match is exact and case-sensitive. ``"Python"`` will not match a record
    stored as ``"python"``, and partial strings will not match. Normalize skill
    names before indexing and before filtering if you need consistent matches.

    Args:
        skill: The skill name to match, such as ``"python"`` or ``"sql"``.
            Must equal the value stored in ``metadata.skill`` exactly.

    Returns:
        A ``models.Filter`` with a single ``must`` condition requiring
        ``metadata.skill`` to equal ``skill``. Records that lack the field
        or have a different value are excluded.

    Example:
        >>> filter = skill_filter("python")
        >>> results = client.search(
        ...     collection_name="candidates",
        ...     query_vector=embedding,
        ...     query_filter=filter,
        ...     limit=5,
        ... )
    """

    return models.Filter(
        must=[
            models.FieldCondition(
                key="metadata.skill",
                match=models.MatchValue(value=skill),
            )
        ]
    )


class RAGApplication:
    """Retrieval-augmented generation (RAG) application that answers questions.

    The application routes each question to a retriever chosen by skill,
    fetches the relevant documents, and passes them with the question to a
    language model chain that generates the answer.

    Attributes:
        retrievers: Mapping of skill names to vector store retrievers. The
            key ``"default"`` is used as a fallback when a skill has no
            dedicated retriever.
        rag_chain: A runnable chain that accepts a dict with ``"question"``
            and ``"documents"`` keys (both strings) and returns the answer
            as a string.

    Example:
        >>> app = RAGApplication(
        ...     retrievers={"python": python_retriever, "default": general_retriever},
        ...     rag_chain=chain,
        ... )
        >>> app.run("How do I open a file?", skill="python")
    """

    def __init__(
        self,
        retrievers: dict[str, VectorStoreRetriever],
        rag_chain: RunnableSerializable[dict[str, str], str],
    ):
        """Initialize the application with its retrievers and generation chain.

        Args:
            retrievers: Mapping of skill names to retrievers. Should include a
                ``"default"`` entry if questions may arrive without a skill
                or with an unknown one.
            rag_chain: Chain that takes ``{"question": ..., "documents": ...}``
                and returns the generated answer.
        """
        self.retrievers = retrievers
        self.rag_chain = rag_chain

    def run(self, question: str, skill: str | None) -> str:
        """Answer a question using documents retrieved for the given skill.

        The retriever is selected by exact match on ``skill``. If ``skill`` is
        ``None`` or has no dedicated retriever, the ``"default"`` retriever is
        used instead. The retrieved documents' text is joined into a single
        string and passed to the RAG chain along with the question.

        Args:
            question: The user's question.
            skill: The skill the question relates to, or ``None`` to use the
                default retriever.

        Returns:
            The answer generated by the RAG chain.

        Raises:
            ValueError: If no retriever matches ``skill`` and no ``"default"``
                retriever is configured.
        """
        retriever = (
            self.retrievers.get(skill)
            if skill in self.retrievers
            else self.retrievers.get("default")
        )

        if retriever is None:
            raise ValueError(
                "Something went wrong. There are no suitable retrievers to serve the request."
            )

        documents = retriever.invoke(question)
        doc_texts = "\n".join([doc.page_content for doc in documents])
        answer = self.rag_chain.invoke({"question": question, "documents": doc_texts})
        return answer


rag_application: RAGApplication | None = None


def initialize() -> None:
    """The initialization function must be called once during the application startup."""

    global rag_application

    qdrant_client = QdrantClient(
        url=os.getenv("QDRANT_URL", "https://localhost:6333"),
        api_key=os.getenv("QDRANT_API_KEY", None),
    )

    try:
        qdrant_client.get_collection(collection_name="rag-app")
    except Exception as e:
        if isinstance(e, UnexpectedResponse) and getattr(e, "status_code", None) == 404:
            print("[i] Qdrant collection `rag-app` not found. Creating embeddings...")
            script_dir = os.path.dirname(os.path.abspath(__file__))
            result = subprocess.run(
                [sys.executable, os.path.join(script_dir, "embeddings.py")],
                capture_output=True,
                text=True,
                cwd=script_dir,
            )
            print(result.stdout)
            if result.returncode != 0:
                print("[err] embeddings.py failed:")
                print(result.stderr)
                raise RuntimeError("embeddings.py failed during startup.")
            print("[i] Collection `rag-app` created. Continuing with startup...")
        else:
            raise

    embedding = OllamaEmbeddings(
        base_url="http://localhost:11434", model="embeddinggemma:latest"
    )

    vector_store = QdrantVectorStore(
        client=qdrant_client, collection_name="rag-app", embedding=embedding
    )
    default_retriever = vector_store.as_retriever(k=4)

    prompt = PromptTemplate(
        template="""You are an assistant for question-answering tasks.
      Use the following documents to answer the question.
      If you don't know the answer, just say that you don't know.
      Use three sentences maximum and keep the answer concise:
      Question: {question}
      Documents: {documents}
      Answer:
      """,
        input_variables=["question", "documents"],
    )

    llm = ChatOllama(
        base_url="http://localhost:11434", model="gemma3n:latest", temperature=0
    )

    rag_chain: RunnableSerializable[dict[str, str], str] = (
        prompt | llm | StrOutputParser()
    )

    skill_scoped_retrievers = {
        skill: vector_store.as_retriever(
            search_kwargs={"k": 4, "filter": skill_filter(skill)}
        )
        for _, skill in skills_module.skill_urls.items()
    }

    skill_scoped_retrievers["default"] = default_retriever

    rag_application = RAGApplication(skill_scoped_retrievers, rag_chain)

    question: str = "What operating systems does nx-ng-starter support?"
    answer = rag_application.run(question, None)
    print("--- startup test ---")
    print("Question:", question)
    print("Answer:", answer.strip())
    print("--- startup test ---")
